// Full browser journey against a fresh, local test database. No real supplier data.
const { chromium } = require('playwright');
const { randomBytes } = require('node:crypto');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const base = process.env.AIRISK_TEST_URL || 'http://127.0.0.1:5057';
const password = randomBytes(24).toString('base64url');
const future = new Date(Date.now() + 60 * 86400000).toISOString().slice(0,10);
const errors = [];
(async () => {
  fs.mkdirSync('test-results', {recursive:true});
  const browser = await chromium.launch({headless:true, ...(process.env.AIRISK_BROWSER ? {executablePath: process.env.AIRISK_BROWSER} : {})});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', async response => {
    if (response.request().method() === 'POST' && response.status() >= 500)
      errors.push(`Server error ${response.status()} on ${new URL(response.url()).pathname}`);
  });
  try {
    const setupToken = process.env.AIRISK_SETUP_TOKEN;
    assert(setupToken && setupToken.length >= 32, 'Set AIRISK_SETUP_TOKEN for the disposable test server and browser');
    await page.goto(base + '/setup?token=' + encodeURIComponent(setupToken));
    await page.getByLabel('Your name').fill('QA Owner');
    await page.getByLabel('Email', {exact:true}).fill('owner@qa.example');
    await page.getByLabel(/^Password/).fill(password);
    await page.getByRole('button', {name:'Create workspace',exact:true}).click();
    await page.waitForURL('**/team');
    await page.getByLabel('Name', {exact:true}).fill('QA Reviewer');
    await page.getByLabel('Email', {exact:true}).fill('reviewer@qa.example');
    await page.getByLabel('Role', {exact:true}).selectOption('reviewer');
    await page.getByLabel('Initial password').fill(password);
    await page.getByRole('button', {name:'Create account',exact:true}).click();
    await page.getByRole('link', {name:'Vendors',exact:true}).click();
    await page.getByLabel('Vendor name').fill('[QA] Example AI supplier');
    await page.getByLabel('Product / service').fill('Enterprise knowledge assistant');
    await page.getByLabel('Can our data be used for training?').selectOption('no');
    await page.getByLabel('Retention and deletion terms').fill('Synthetic test: 30 day retention; deletion verified for fixture.');
    await page.getByLabel('Hosting and processing regions').fill('EU (synthetic)');
    await page.getByLabel('Next vendor review').fill(future);
    await page.getByRole('button', {name:'Add vendor',exact:true}).click();
    await page.waitForURL(/\/vendors\/\d+$/);
    const vendorId = page.url().split('/').pop();

    async function createSystem(name, type='generative', domain='general', autonomy='advisory') {
      await page.goto(base + '/systems/new');
      await page.getByLabel('Use case name').fill(name);
      await page.getByLabel('Department', {exact:true}).fill('Operations');
      await page.getByLabel('Purpose and affected people').fill('Synthetic pilot: employees retrieve policy information. Validate accuracy, access controls and the review decision.');
      await page.getByLabel('Vendor / product').selectOption(vendorId);
      await page.getByLabel('Model or product version').fill('Evaluation fixture v1');
      await page.getByLabel('AI technology').selectOption(type);
      await page.getByLabel('Most sensitive data used').selectOption('confidential');
      await page.getByLabel('Authority to act').selectOption(autonomy);
      if (type!=='predictive') await page.getByLabel('Retrieves information').check();
      await page.getByLabel('EU scope', {exact:true}).selectOption('yes');
      await page.getByLabel('Our role', {exact:true}).selectOption('deployer');
      await page.getByLabel('Use area', {exact:true}).selectOption(domain);
      await page.getByLabel('Prohibited-practice screening', {exact:true}).selectOption('none');
      await page.getByLabel('Scope rationale, exceptions and restrictions').fill('Synthetic screening for application workflow testing. Not a real deployment assessment.');
      await page.getByRole('button', {name:'Save use case',exact:true}).click();
      await page.waitForURL(/\/systems\/\d+$/);
      await page.getByRole('button', {name:'Start new assessment',exact:true}).click();
      await page.waitForURL(/\/assessments\/\d+$/);
      return page.url();
    }
    async function claudeHandoff(mode) {
      await page.getByRole('link',{name:'Claude assistance',exact:true}).click();
      await page.getByLabel('Claude workspace',{exact:true}).selectOption('Claude Enterprise');
      await page.getByLabel('How should Claude help?',{exact:true}).selectOption(mode);
      for (const box of await page.locator('input[name="risk_ids"]').all()) await box.uncheck();
      await page.locator('input[name="risk_ids"]').first().check();
      await page.getByRole('button',{name:'Prepare prompt',exact:true}).click();
      await page.waitForURL(/\/claude\/\d+$/);
      const prompt = await page.getByLabel('Prepared prompt',{exact:true}).inputValue();
      const shape = prompt.match(/RESPONSE SHAPE[^\n]*\n([\s\S]*?)\n\nASSESSMENT DATA:/);
      assert(shape,'The prompt contains a response schema');
      // This fixture exercises the handoff contract; it does not call Claude.
      const suggestion = JSON.parse(shape[1]);
      suggestion.summary='Synthetic Claude-response fixture for the browser workflow.';
      suggestion.risks[0].rationale='Synthetic suggested reasoning: validate source freshness before relying on answers.';
      suggestion.risks[0].likelihood=3;
      suggestion.risks[0].impact=4;
      await page.getByLabel('Model name shown in Claude (optional)').fill('Synthetic browser fixture');
      await page.getByLabel('Claude’s JSON response').fill(JSON.stringify(suggestion));
      await page.getByRole('button',{name:'Preview suggestions',exact:true}).click();
      assert(await page.getByRole('heading',{name:'Claude’s suggestions',exact:true}).isVisible());
      if (mode==='draft') {
        await page.locator('input[name="risk_ids"]').check();
        await page.getByLabel('I reviewed the selected reasoning and ratings against the available evidence.').check();
        await page.getByRole('button',{name:'Apply selected suggestions to draft',exact:true}).click();
      } else {
        assert.equal(await page.getByRole('button',{name:'Apply selected suggestions to draft',exact:true}).count(),0);
        await page.getByRole('link',{name:'Return to review and decision →',exact:true}).click();
      }
    }
    const assessmentUrl = await createSystem('[QA] Internal policy assistant');
    const aid = assessmentUrl.split('/').pop();
    await page.getByText('Add a risk specific to this use case', {exact:true}).click();
    await page.getByLabel('Risk title', {exact:true}).fill('Synthetic domain-specific failure');
    await page.getByLabel('Scenario and affected people').fill('The assistant may cite a withdrawn local policy, affecting employees who follow it.');
    await page.getByLabel('Proposed control guidance').fill('Test the withdrawal and replacement process with a synthetic policy.');
    await page.getByLabel('Evidence needed').fill('A dated withdrawal and retrieval test for the deployed configuration.');
    await page.getByRole('button', {name:'Add custom risk',exact:true}).click();
    await claudeHandoff('draft');
    await page.locator('#evidence summary').click();
    await page.getByLabel('Evidence title').fill('Synthetic permission and quality evaluation');
    await page.getByLabel('Review or expiry date').fill(future);
    await page.getByLabel('What does the evidence demonstrate?').fill('Fixture for workflow verification: representative questions, denied document access, synthetic adversarial input and human escalation. This tests the risk application, not a real AI vendor.');
    await page.getByRole('button', {name:'Record evidence',exact:true}).click();
    await page.waitForURL(/#evidence$/);
    const riskIds = await page.locator('details.risk').evaluateAll(nodes => nodes.map(n=>n.id));
    assert(riskIds.length>=12);
    for (const id of riskIds) {
      const card = page.locator('#'+id);
      if (!(await card.getAttribute('open')!==null)) await card.locator('summary').click();
      await card.getByLabel('Inherent likelihood', {exact:true}).selectOption('4');
      await card.getByLabel('Inherent impact', {exact:true}).selectOption('4');
      await card.getByLabel('Residual likelihood', {exact:true}).selectOption('2');
      await card.getByLabel('Residual impact', {exact:true}).selectOption('3');
      await card.getByLabel('Assessment rationale').fill('Synthetic assessment: realistic exposure was reviewed; this record exercises persistence and independent approval.');
      await card.getByLabel('Controls actually in place').fill('Synthetic controls: access restrictions, reviewed answers and manual fallback were exercised in the fixture.');
      await card.locator('input[name="evidence_ids"]').check();
      await card.getByRole('button', {name:'Save risk',exact:true}).click();
      await page.waitForURL(new RegExp('#'+id+'$'));
    }
    await page.getByRole('button',{name:'Request independent review',exact:true}).click();
    await page.waitForURL(new RegExp('/assessments/'+aid+'$'));
    assert.equal(await page.locator('.risk button').count(),0,'Submitted risk cards are locked');
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByLabel('Email',{exact:true}).fill('reviewer@qa.example');
    await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await page.goto(assessmentUrl);
    await page.getByRole('button',{name:'Verify evidence',exact:true}).click();
    await page.getByText('Return to author for changes',{exact:true}).click();
    const returnReason = 'Confirm the synthetic access-control evaluation covers restricted documents.';
    await page.getByLabel('What needs to change?').fill(returnReason);
    await page.getByRole('button',{name:'Return to draft',exact:true}).click();
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByLabel('Email',{exact:true}).fill('owner@qa.example');
    await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await page.goto(assessmentUrl);
    assert(await page.getByText(returnReason,{exact:true}).first().isVisible(),'Author can read the requested change');
    await page.getByRole('button',{name:'Request independent review',exact:true}).click();
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByLabel('Email',{exact:true}).fill('reviewer@qa.example');
    await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await page.goto(assessmentUrl);
    await claudeHandoff('review');
    await page.getByLabel('Role, applicable obligations, timing and rationale').fill('Synthetic review: deployer role; no prohibited or Annex III use in this fixture. Record literacy, transparency and review dates. Sources: Articles 5, 6, 26 and 50 of the current EU AI Act.');
    await page.getByRole('button',{name:'Save applicability review',exact:true}).click();
    await page.getByLabel('Reason, restrictions and accepted residual risks').fill('Approved for synthetic workflow testing only, within the recorded purpose. Reassess on model, data or vendor changes.');
    await page.getByLabel('Next review date (required for approval)').fill(future);
    await page.getByRole('button',{name:'Record decision',exact:true}).click();
    await page.waitForURL(new RegExp('/assessments/'+aid+'$'));
    assert(await page.getByRole('heading',{name:'Approved by QA Reviewer'}).isVisible());
    const response = await page.request.get(base+'/assessments/'+aid+'/export.json');
    const payload = await response.json();
    assert.equal(payload.state,'approved');
    assert.equal(payload.risks.length,riskIds.length);
    assert.deepEqual(payload.approval_blockers,[]);
    assert.equal(payload.claude_assistance.length,2);
    const csv = await page.request.get(base+'/assessments/'+aid+'/export.csv');
    assert.equal(csv.status(),200);
    await page.goto(base+'/assessments/'+aid+'/export.html');
    assert(await page.getByRole('heading',{name:'Decision record'}).isVisible());
    await page.pdf({path:'test-results/assessment-report.pdf',format:'A4',printBackground:true});
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByLabel('Email',{exact:true}).fill('owner@qa.example');
    await page.getByLabel('Password',{exact:true}).fill(password);
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await createSystem('[QA] Recruitment screening','predictive','employment');
    assert(await page.getByRole('heading',{name:'Potential high-risk use',exact:true}).isVisible());
    assert.equal(await page.locator('summary').filter({hasText:'Instructions hidden in untrusted content'}).count(),0);
    await createSystem('[QA] Customer service agent','agentic','general','assisted');
    assert.equal(await page.locator('summary').filter({hasText:'An agent acts beyond its intended authority'}).count(),1);
    await page.goto(base);
    await page.screenshot({path:'test-results/desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'test-results/mobile.png',fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page must not overflow horizontally');
    await page.goto(assessmentUrl);
    assert(await page.getByRole('heading',{name:'Approved by QA Reviewer'}).isVisible());
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile assessment must not overflow horizontally');
    assert.deepEqual(errors,[]);
    fs.rmSync('test-results/failure.png', {force:true});
    console.log(JSON.stringify({status:'passed',journeys:['local setup','team creation','vendor due diligence','internal RAG assessment','custom AI risk','Claude draft handoff with synthetic response','independent evidence verification','reviewer change request and resubmission','Claude review handoff with synthetic response','approval','JSON/CSV/PDF export','predictive hiring triage','agentic risk routing','mobile layout'],risksAssessed:riskIds.length,consoleErrors:errors.length},null,2));
  } catch(error) {
    await page.screenshot({path:'test-results/failure.png',fullPage:true});
    throw error;
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
